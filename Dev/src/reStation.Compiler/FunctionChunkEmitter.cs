// @module: reStation.Compiler.FunctionChunkEmitter
// @purpose: Packs lifted MIPS functions, binary-search dispatch tables, and IRecompModule entry points into <= 320 LOC generated C# files.
// @depends-on: System.Text, reStation.Compiler.ExeScanHelpers, reStation.Compiler.MipsLifter
// @exports: FunctionChunkEmitter
// @owner: devv-compiler (T5)

using System.Text;

namespace reStation.Compiler;

/// <summary>Emits chunked partial C# files (<c>PartNNN.g.cs</c>, <c>DispatchNN.g.cs</c>, <c>MidDispatchNN.g.cs</c>, <c>&lt;Class&gt;.g.cs</c>).</summary>
public static class FunctionChunkEmitter
{
    public const int MaxGeneratedFileLines = 320;
    private const int PartWrapperLines = 8;
    private const int MaxPartBodyLines = MaxGeneratedFileLines - PartWrapperLines;
    private const int MaxCasesPerDispatchFile = 240;

    /// <summary>Lifts all functions in <paramref name="spec"/> and writes all generated files into <paramref name="outDir"/>.</summary>
    public static List<string> EmitModule(
        string outDir,
        string rootNamespace,
        GeneratedExeSpec spec,
        Func<uint, uint> readWord,
        IReadOnlySet<uint>? rdataTargets = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outDir);
        ArgumentException.ThrowIfNullOrWhiteSpace(rootNamespace);
        ArgumentNullException.ThrowIfNull(spec);
        ArgumentNullException.ThrowIfNull(readWord);

        string modDir = Path.Combine(outDir, spec.FolderName);
        if (Directory.Exists(modDir)) Directory.Delete(modDir, recursive: true);
        Directory.CreateDirectory(modDir);

        var emittedFiles = new List<string>();
        var allUnits = new List<LiftedUnit>(spec.Functions.Count);
        var midEntries = new List<(uint Addr, string MethodName)>();
        foreach (GeneratedFnSpec fn in spec.Functions)
        {
            allUnits.AddRange(LiftWithinCap(fn.MethodName, fn.Addr, fn.EndAddr, readWord, rdataTargets, out List<uint> fnMids));
            foreach (uint mid in fnMids) midEntries.Add((mid, fn.MethodName));
        }

        int fileIndex = 0;
        var current = new List<string>(MaxPartBodyLines);
        void FlushCurrent()
        {
            if (current.Count == 0) return;
            var sb = new StringBuilder(current.Count * 48);
            sb.AppendLine($"// <auto-generated /> {spec.ExeName} lifted functions part {fileIndex:D3}");
            sb.AppendLine("using reStation.Contracts;");
            sb.AppendLine();
            sb.AppendLine($"namespace {rootNamespace}.{spec.FolderName};");
            sb.AppendLine();
            sb.AppendLine($"public sealed partial class {spec.ClassName}");
            sb.AppendLine("{");
            foreach (string line in current) sb.AppendLine(line);
            sb.AppendLine("}");
            string path = Path.Combine(modDir, $"Part{fileIndex:D3}.g.cs");
            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
            emittedFiles.Add(path);
            fileIndex++;
            current.Clear();
        }

        foreach (LiftedUnit unit in allUnits)
        {
            int sep = current.Count > 0 ? 1 : 0;
            if (current.Count > 0 && current.Count + sep + unit.Lines.Count > MaxPartBodyLines)
                FlushCurrent();
            if (current.Count > 0) current.Add(string.Empty);
            current.AddRange(unit.Lines);
        }
        FlushCurrent();

        var fnEntries = spec.Functions.OrderBy(f => f.Addr).Select(f => (f.Addr, $"{f.MethodName}(cpu)")).ToList();
        List<uint> chunkMaxAddrs = EmitDispatchFiles(modDir, rootNamespace, spec, "Dispatch", "TryDispatch", fnEntries, emittedFiles);
        var sortedMids = midEntries.OrderBy(m => m.Addr).DistinctBy(m => m.Addr)
            .Select(m => (m.Addr, $"{m.MethodName}_At(cpu, 0x{m.Addr:X8}U)")).ToList();
        List<uint> midMaxAddrs = EmitDispatchFiles(modDir, rootNamespace, spec, "MidDispatch", "TryMidDispatch", sortedMids, emittedFiles);
        EmitModuleHeader(modDir, rootNamespace, spec, chunkMaxAddrs, midMaxAddrs, emittedFiles);
        return emittedFiles;
    }

    private static List<LiftedUnit> LiftWithinCap(
        string methodName, uint addr, uint endAddr, Func<uint, uint> readWord, IReadOnlySet<uint>? rdataTargets, out List<uint> midEntries)
    {
        int chunk = MipsLifter.DefaultChunkInstructions;
        bool forceChunk = false;
        while (true)
        {
            List<LiftedUnit> units = MipsLifter.LiftFunction(methodName, addr, endAddr, readWord, rdataTargets, out midEntries, chunk, forceChunk);
            if (units.All(u => u.Lines.Count <= MaxPartBodyLines) || chunk <= MipsLifter.MinChunkInstructions)
                return units;
            chunk = Math.Max(MipsLifter.MinChunkInstructions, chunk / 2);
            forceChunk = true;
        }
    }

    private static List<uint> EmitDispatchFiles(
        string modDir, string rootNamespace, GeneratedExeSpec spec, string filePrefix, string helperPrefix,
        IReadOnlyList<(uint Pc, string CallExpr)> entries, List<string> emittedFiles)
    {
        var maxAddrs = new List<uint>();
        int part = 0;
        for (int i = 0; i < entries.Count; i += MaxCasesPerDispatchFile)
        {
            int take = Math.Min(MaxCasesPerDispatchFile, entries.Count - i);
            var sb = new StringBuilder();
            sb.AppendLine($"// <auto-generated /> {spec.ExeName} {filePrefix} chunk {part:D2}");
            sb.AppendLine("using reStation.Contracts;");
            sb.AppendLine();
            sb.AppendLine($"namespace {rootNamespace}.{spec.FolderName};");
            sb.AppendLine();
            sb.AppendLine($"public sealed partial class {spec.ClassName}");
            sb.AppendLine("{");
            sb.AppendLine($"    private static bool {helperPrefix}{part:D2}(IReStationCpu cpu, uint pc)");
            sb.AppendLine("    {");
            sb.AppendLine("        switch (pc)");
            sb.AppendLine("        {");
            for (int k = 0; k < take; k++)
            {
                (uint pc, string callExpr) = entries[i + k];
                sb.AppendLine($"            case 0x{pc:X8}U: {callExpr}; return true;");
            }
            sb.AppendLine("            default: return false;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            string path = Path.Combine(modDir, $"{filePrefix}{part:D2}.g.cs");
            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
            emittedFiles.Add(path);
            maxAddrs.Add(entries[i + take - 1].Pc);
            part++;
        }
        return maxAddrs;
    }

    private static void EmitModuleHeader(
        string modDir, string rootNamespace, GeneratedExeSpec spec,
        IReadOnlyList<uint> chunkMaxAddrs, IReadOnlyList<uint> midMaxAddrs, List<string> emittedFiles)
    {
        if (spec.IsOverlay)
        {
            if (spec.LoadRamAddress == 0U)
                throw new ArgumentException($"Overlay spec '{spec.ExeName}' requires non-zero LoadRamAddress.", nameof(spec));
            if (spec.ContentSizeBytes <= 0)
                throw new ArgumentException($"Overlay spec '{spec.ExeName}' requires positive ContentSizeBytes.", nameof(spec));
            if (string.IsNullOrWhiteSpace(spec.ContentSha256Hex) || spec.ContentSha256Hex.Length != 64 || !spec.ContentSha256Hex.All(Uri.IsHexDigit))
                throw new ArgumentException($"Overlay spec '{spec.ExeName}' requires a 64-character hex ContentSha256Hex.", nameof(spec));
        }

        string baseInterface = spec.IsOverlay ? "IOverlayRecompModule" : "IRecompModule";
        var sb = new StringBuilder();
        sb.AppendLine($"// <auto-generated /> {spec.ExeName} {baseInterface} entry point");
        sb.AppendLine("using reStation.Contracts;");
        sb.AppendLine();
        sb.AppendLine($"namespace {rootNamespace}.{spec.FolderName};");
        sb.AppendLine();
        sb.AppendLine($"public sealed partial class {spec.ClassName} : {baseInterface}");
        sb.AppendLine("{");
        sb.AppendLine($"    public int ExeId => {spec.ExeId};");
        sb.AppendLine($"    public string ExeName => \"{EscapeString(spec.ExeName)}\";");
        sb.AppendLine($"    public uint TextStart => 0x{spec.TextStart:X8}U;");
        sb.AppendLine($"    public uint TextEnd => 0x{spec.TextEnd:X8}U;");
        if (spec.IsOverlay)
        {
            sb.AppendLine($"    public uint LoadRamAddress => 0x{spec.LoadRamAddress:X8}U;");
            sb.AppendLine($"    public int ContentSizeBytes => {spec.ContentSizeBytes};");
            sb.AppendLine($"    public string ContentSha256Hex => \"{EscapeString(spec.ContentSha256Hex)}\";");
        }
        sb.AppendLine();
        sb.AppendLine("    public bool TryExecuteFunction(IReStationCpu cpu, uint pc)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (pc < TextStart || pc >= TextEnd) return false;");
        sb.AppendLine("        if (TryDispatchExact(cpu, pc)) return true;");
        sb.AppendLine("        return TryExecuteMidFunction(cpu, pc);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static bool TryDispatchExact(IReStationCpu cpu, uint pc)");
        sb.AppendLine("    {");
        EmitDispatcherBody(sb, chunkMaxAddrs, "TryDispatch");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public bool TryExecuteMidFunction(IReStationCpu cpu, uint pc)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (pc < TextStart || pc >= TextEnd) return false;");
        EmitDispatcherBody(sb, midMaxAddrs, "TryMidDispatch");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        string path = Path.Combine(modDir, $"{spec.ClassName}.g.cs");
        File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
        emittedFiles.Add(path);
    }

    private static void EmitDispatcherBody(StringBuilder sb, IReadOnlyList<uint> maxAddrs, string helperPrefix)
    {
        if (maxAddrs.Count == 0) { sb.AppendLine("        return false;"); return; }
        if (maxAddrs.Count > 40)
        {
            for (int i = 0; i < maxAddrs.Count; i++)
                sb.AppendLine($"        if (pc <= 0x{maxAddrs[i]:X8}U) return {helperPrefix}{i:D2}(cpu, pc);");
            sb.AppendLine("        return false;");
            return;
        }
        EmitDispatchTree(sb, maxAddrs, 0, maxAddrs.Count - 1, "        ", helperPrefix);
    }

    private static void EmitDispatchTree(StringBuilder sb, IReadOnlyList<uint> maxAddrs, int lo, int hi, string indent, string helperPrefix)
    {
        if (lo == hi) { sb.AppendLine($"{indent}return {helperPrefix}{lo:D2}(cpu, pc);"); return; }
        int mid = (lo + hi) >> 1;
        sb.AppendLine($"{indent}if (pc <= 0x{maxAddrs[mid]:X8}U)");
        sb.AppendLine($"{indent}{{");
        EmitDispatchTree(sb, maxAddrs, lo, mid, indent + "    ", helperPrefix);
        sb.AppendLine($"{indent}}}");
        EmitDispatchTree(sb, maxAddrs, mid + 1, hi, indent, helperPrefix);
    }

    private static string EscapeString(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
