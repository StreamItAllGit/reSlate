using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using reEngine.Core.Decomp;

namespace reStation.Decomp;

/// <summary>
/// Generates original clean-room <c>MPL-2.0</c> Ghidra batch Jython scripts and deterministic JSON descriptors
/// for PS-X EXE memory mapping, BSS zero-clearing, overlay loading, coalesced modules, and normalized C exports.
/// </summary>
internal static class PsxGhidraScriptTemplates
{
    public const string LoaderScriptFileName = "PsxCleanExeLoader.py";
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull
    };

    /// <summary>Generates the clean-room <c>stdint.h</c> + <c>PsxCallbackFn</c> typedef preamble for normalized C outputs.</summary>
    public static string GeneratePsxCleanCompatPreamble() => """
        #include <stdint.h>
        typedef void (*PsxCallbackFn)(void);
        """;

    /// <summary>Writes <c>psx-layout.json</c> describing boot executable, overlays, and initial memory blocks.</summary>
    public static void WriteLayoutJson(string layoutPath, PsxLoadedProgramLayout layout)
    {
        var regions = new List<object>
        {
            new { name = ".text_data", startAddress = $"0x{layout.BootExe.Header.TextAddr:X8}", sizeBytes = layout.BootExe.Header.TextSize, read = true, write = true, execute = true },
            new { name = ".bss", startAddress = $"0x{layout.BootExe.Header.BssAddr:X8}", sizeBytes = layout.BootExe.Header.BssSize, read = true, write = true, execute = false }
        };
        File.WriteAllText(layoutPath, JsonSerializer.Serialize(new
        {
            schemaVersion = 1,
            bootExecutable = new
            {
                slotId = layout.BootExe.SlotId,
                relativePath = layout.BootExe.RelativePath,
                sha256 = layout.BootExe.Sha256Hex,
                pc0 = $"0x{layout.BootExe.Header.Pc0:X8}",
                gp0 = $"0x{layout.BootExe.Header.Gp0:X8}",
                tAddr = $"0x{layout.BootExe.Header.TextAddr:X8}",
                tSize = layout.BootExe.Header.TextSize,
                bAddr = $"0x{layout.BootExe.Header.BssAddr:X8}",
                bSize = layout.BootExe.Header.BssSize
            },
            overlays = layout.Overlays.Select(o => new
            {
                slotId = o.SlotId,
                relativePath = o.RelativePath,
                sha256 = o.Sha256Hex,
                loadAddress = $"0x{o.LoadAddress:X8}",
                entryAddress = $"0x{o.EntryAddress:X8}",
                byteLength = o.ByteLength,
                bssAddress = $"0x{o.BssAddress:X8}",
                bssSize = o.BssSize
            }),
            memoryRegions = regions
        }, JsonOptions), new UTF8Encoding(false));
    }

    /// <summary>Writes deterministic offline <c>ghidra-batch-plan.json</c> metadata.</summary>
    public static void WriteBatchPlanJson(
        string planPath,
        OfflineToolchainStatus toolchain,
        string analyzeExe,
        IReadOnlyList<string> args,
        string cmdPreview)
    {
        File.WriteAllText(planPath, JsonSerializer.Serialize(new
        {
            schemaVersion = 1,
            sleighLanguageId = PsxGteSlaExtension.SleighLanguageId,
            offlineOnly = true,
            toolchainAvailable = toolchain.IsAvailable,
            toolchainDirectory = toolchain.ToolchainDirectory,
            analyzeHeadless = analyzeExe,
            javaExecutable = toolchain.JavaExecutablePath,
            arguments = args,
            commandLinePreview = cmdPreview
        }, JsonOptions), new UTF8Encoding(false));
    }

    /// <summary>
    /// Emits an original clean-room Ghidra batch script reading <c>psx-layout.json</c> without external GPLv3 plugins.
    /// </summary>
    public static string GenerateCleanExeLoaderScript() => """
        # Clean-Room PS-X EXE + Multi-Overlay Ghidra Batch Script (MPL-2.0)
        # Generated by reSlate.Decomp — zero external GPL loaders or copyrighted headers.
        #@category reSlate.PS1

        import json
        import os
        import re
        from ghidra.app.decompiler import DecompInterface
        from ghidra.program.model.data import ArrayDataType

        def classify_coalesced_unit(fn_name, c_code):
            low = (fn_name or "").lower()
            if "gte" in low or "gte_" in (c_code or ""):
                return "sdk/libgte/gte_math.c"
            if "gpu" in low or "drawotag" in low or "dispenv" in low:
                return "sdk/libgpu/gpu_primitives.c"
            if low.startswith("cd_") or "cdcontrol" in low or "cdread" in low:
                return "sdk/libcd/cd_stream.c"
            if "spu" in low or "vag" in low or "vab" in low:
                return "sdk/libspu/spu_audio.c"
            if "pad" in low or "sio" in low or "vsync" in low:
                return "sdk/libetc/sys_io.c"
            if "ovl" in low:
                return "overlays/overlay_subsystem.c"
            if low in ("psx_entry", "main") or low.startswith("init_"):
                return "src/core_mainloop/core_mainloop.c"
            return "src/gameplay/gameplay.c"

        def normalize_callbacks(c_code):
            out = re.sub(r"\(\s*code\s*\*\s*\)(?!\s*\(\s*uintptr_t\s*\))", "(PsxCallbackFn)(uintptr_t)", c_code)
            return re.sub(r"\bcode\s*\*", "PsxCallbackFn", out)

        def collect_typed_array_externs():
            externs = []
            lines = ["/* Typed array externs emitted by reSlate.Decomp (MPL-2.0) */"]
            listing = currentProgram.getListing()
            for data in listing.getDefinedData(True):
                sym = data.getPrimarySymbol()
                if sym is None:
                    continue
                dt = data.getDataType()
                if isinstance(dt, ArrayDataType):
                    elem_cnt = int(dt.getNumElements())
                    elem_sz = int(dt.getElementLength())
                    c_ty = "u8" if elem_sz == 1 else ("u16" if elem_sz == 2 else "u32")
                    nm = sym.getName()
                    externs.append({"name": nm, "elementType": c_ty, "elementCount": elem_cnt})
                    lines.append("extern %s %s[%d];" % (c_ty, nm, elem_cnt))
            return externs, "\n".join(lines) + "\n"

        def main():
            args = getScriptArgs()
            if len(args) < 2:
                raise RuntimeError("Expected <psx-layout.json> <export-dir> script arguments.")
            layout_path = os.path.abspath(args[0])
            export_dir = os.path.abspath(args[1])
            if not os.path.isdir(export_dir):
                os.makedirs(export_dir)

            with open(layout_path, "r") as fp:
                layout = json.load(fp)

            mem = currentProgram.getMemory()
            addr_space = currentProgram.getAddressFactory().getDefaultAddressSpace()

            for block_spec in layout.get("memoryRegions", []):
                name = str(block_spec["name"])
                start_va = int(block_spec["startAddress"], 16)
                size = int(block_spec["sizeBytes"])
                if size <= 0:
                    continue
                addr = addr_space.getAddress(start_va)
                if mem.getBlock(addr) is None:
                    blk = mem.createUninitializedBlock(name, addr, size, False)
                    blk.setRead(bool(block_spec.get("read", True)))
                    blk.setWrite(bool(block_spec.get("write", True)))
                    blk.setExecute(bool(block_spec.get("execute", False)))

            boot_pc = int(layout["bootExecutable"]["pc0"], 16)
            boot_addr = addr_space.getAddress(boot_pc)
            addEntryPoint(boot_addr)
            createFunction(boot_addr, "psx_entry")

            decomp = DecompInterface()
            decomp.openProgram(currentProgram)
            fn_entries = []
            c_chunks = [
                "/* Clean-room Ghidra export generated by reSlate.Decomp (MPL-2.0) */\n",
                "#include <stdint.h>\ntypedef void (*PsxCallbackFn)(void);\n"
            ]

            fm = currentProgram.getFunctionManager()
            for fn in fm.getFunctions(True):
                ep = fn.getEntryPoint().getOffset()
                body_len = fn.getBody().getNumAddresses()
                res = decomp.decompileFunction(fn, 30, monitor)
                c_code = res.getDecompiledFunction().getC() if (res is not None and res.decompileCompleted()) else ""
                unit = classify_coalesced_unit(fn.getName(), c_code)
                fn_entries.append({
                    "name": fn.getName(),
                    "address": "0x%08x" % ep,
                    "size": int(body_len),
                    "coalescedModule": unit
                })
                if c_code:
                    norm = normalize_callbacks(c_code)
                    c_chunks.append("/* @coalesced-module %s | %s @ 0x%08x */\n%s\n" % (unit, fn.getName(), ep, norm))

            externs, externs_h = collect_typed_array_externs()
            with open(os.path.join(export_dir, "globals.json"), "w") as out_g:
                json.dump({"globals": externs}, out_g, indent=2)
            with open(os.path.join(export_dir, "psx_globals_externs.h"), "w") as out_h:
                out_h.write(externs_h)
            with open(os.path.join(export_dir, "functions.json"), "w") as out_json:
                json.dump({"engineId": "reSlate", "preservedTiers": ["D1_Raw", "D2_Structured", "D3_Mapped", "D4_CleanSource"], "functions": fn_entries}, out_json, indent=2)
            with open(os.path.join(export_dir, "exported.c"), "w") as out_c:
                out_c.write("\n".join(c_chunks))

        if __name__ == "__main__":
            main()
        """;
}
